-- ---------------------------------------------------------------------------
-- Read projections — SECURITY DEFINER so they resolve author display names
-- without opening the users table (same posture as league_standings). Each one
-- gates on membership, so a non-member gets nothing.
-- ---------------------------------------------------------------------------

-- One page of a league's feed, newest first, enriched with author name, like +
-- reply counts, and whether the caller has liked each post.
create or replace function public.league_feed(
  p_league integer,
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id bigint,
  author_id uuid,
  author_name text,
  body text,
  is_system boolean,
  system_kind text,
  created_at timestamptz,
  like_count integer,
  reply_count integer,
  liked_by_me boolean
)
language sql
security definer
set search_path = ''
stable
as $$
  select
    p.id,
    p.author_id,
    u.display_name as author_name,
    p.body,
    p.is_system,
    p.system_kind,
    p.created_at,
    (select count(*) from public.league_post_likes l where l.post_id = p.id)::integer,
    (select count(*) from public.league_post_replies r where r.post_id = p.id)::integer,
    exists (
      select 1 from public.league_post_likes l
      where l.post_id = p.id and l.user_id = (select auth.uid())
    )
  from public.league_posts p
  left join public.users u on u.id = p.author_id
  where p.league_id = p_league
    and public.is_league_member(p_league)
  order by p.created_at desc
  limit greatest(p_limit, 0)
  offset greatest(p_offset, 0);
$$;

-- The flat reply thread under one post, oldest first, with author names.
create or replace function public.league_post_thread(p_post bigint)
returns table (
  id bigint,
  author_id uuid,
  author_name text,
  body text,
  created_at timestamptz
)
language sql
security definer
set search_path = ''
stable
as $$
  select
    r.id,
    r.author_id,
    u.display_name as author_name,
    r.body,
    r.created_at
  from public.league_post_replies r
  left join public.users u on u.id = r.author_id
  where r.post_id = p_post
    and public.is_league_member(public.post_league_id(p_post))
  order by r.created_at asc;
$$;

